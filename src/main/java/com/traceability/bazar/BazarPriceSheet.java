package com.traceability.bazar;

import com.traceability.inventory.LabelFonts;
import com.traceability.inventory.LabelTextFitter;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.text.DecimalFormat;
import java.text.DecimalFormatSymbols;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Objects;

/**
 * Bazar POS B7b — the event's A4 price sheet: per product + colour its number (#12), name, colour, the sizes still at
 * the bazar and the bazar price. PDFBox with the labels' embedded Noto Sans + Noto Sans Arabic (Arabic shaped and
 * bidi-ordered by LabelTextFitter); Arabic sheets mirror the columns and right-align the text. Money "960 EGP" with
 * Latin digits (R2 rule). Read-only: built from {@link BazarCatalogService#catalog}.
 */
public final class BazarPriceSheet {

    private BazarPriceSheet() {}

    private record Words(String title, String number, String product, String colour, String sizes, String price,
                         String soldOut, String footer, String page, String of, String noProducts, String egp) {}

    private static final Words EN = new Words("Bazar price sheet", "#", "Product", "Colour", "Sizes at the bazar",
        "Price", "Sold out", "Bazar prices · generated by Traced", "Page", "of",
        "No products at this bazar yet.", "EGP");
    private static final Words AR = new Words("قائمة أسعار البازار", "#", "المنتج", "اللون", "المقاسات المتوفرة",
        "السعر", "نفد", "أسعار البازار · من Traced", "صفحة", "من",
        "لا توجد منتجات في هذا البازار بعد.", "ج.م");

    static boolean arabic(String lang) {
        return lang != null && lang.toLowerCase(Locale.ROOT).startsWith("ar");
    }

    private static final float MARGIN = 40f;
    private static final float WIDTH = PDRectangle.A4.getWidth() - 2 * MARGIN;   // 515
    private static final float ROW_H = 24f;
    private static final float SIZE = 10f;
    /** Columns (LTR): #, product, colour, sizes, price — x from the left margin and width. */
    private static final float[] COL_X = {0f, 44f, 232f, 326f, 416f};
    private static final float[] COL_W = {40f, 184f, 90f, 86f, 99f};
    private static final boolean[] COL_END = {false, false, false, false, true};   // price aligned to its end

    public static byte[] pdf(BazarCatalogService.Catalog c, String lang) {
        Words w = arabic(lang) ? AR : EN;
        boolean rtl = arabic(lang);
        List<BazarCatalogService.Group> groups = c.groups().stream()
            .filter(g -> g.sizes().stream().anyMatch(s -> s.price() != null)).toList();
        int firstPageRows = (int) ((PDRectangle.A4.getHeight() - 2 * MARGIN - 120f - 40f) / ROW_H);
        int otherPageRows = (int) ((PDRectangle.A4.getHeight() - 2 * MARGIN - 50f - 40f) / ROW_H);
        int pages = groups.size() <= firstPageRows ? 1
            : 1 + (int) Math.ceil((groups.size() - firstPageRows) / (double) otherPageRows);
        String generated = LocalDateTime.now(ZoneId.of("Africa/Cairo"))
            .format(rtl ? NUMERIC_TIME : DateTimeFormatter.ofPattern("d MMM yyyy HH:mm", Locale.ENGLISH));

        try (PDDocument doc = new PDDocument()) {
            LabelFonts.Loaded fonts = new LabelFonts.Loaded(doc);
            int pageNo = 0;
            int i = 0;
            do {
                pageNo++;
                PDPage page = new PDPage(PDRectangle.A4);
                doc.addPage(page);
                try (PDPageContentStream cs = new PDPageContentStream(doc, page)) {
                    float y = PDRectangle.A4.getHeight() - MARGIN;
                    if (pageNo == 1) {
                        cell(cs, fonts, "traced", 0f, WIDTH, y, 14f, LabelFonts.Face.BOLD, rtl, false);
                        cell(cs, fonts, c.eventName(), 0f, WIDTH, y, 16f, LabelFonts.Face.BOLD, rtl, true);
                        y -= 18f;
                        cell(cs, fonts, w.title(), 0f, 200f, y, 9f, LabelFonts.Face.REGULAR, rtl, false);
                        cell(cs, fonts, place(c, rtl), 0f, WIDTH, y, 9f, LabelFonts.Face.REGULAR, rtl, true);
                        y -= 14f;
                        rule(cs, y, 1.2f);
                        y -= 30f;
                    }
                    y = header(cs, fonts, w, y, rtl);
                    int rows = pageNo == 1 ? firstPageRows : otherPageRows;
                    if (groups.isEmpty()) {
                        cell(cs, fonts, w.noProducts(), 0f, WIDTH, y, SIZE, LabelFonts.Face.REGULAR, rtl, false);
                    }
                    for (int r = 0; r < rows && i < groups.size(); r++, i++) {
                        BazarCatalogService.Group g = groups.get(i);
                        String[] cells = {
                            g.number() == null ? "" : "#" + g.number(),
                            g.title(),
                            g.colour() == null ? "—" : g.colour(),
                            sizes(g, w),
                            price(g, w)};
                        for (int col = 0; col < cells.length; col++) {
                            cell(cs, fonts, cells[col], COL_X[col], COL_W[col], y, SIZE,
                                col == 0 || col == 4 ? LabelFonts.Face.BOLD : LabelFonts.Face.REGULAR, rtl, COL_END[col]);
                        }
                        rule(cs, y - 8f, 0.3f);
                        y -= ROW_H;
                    }
                    String foot = w.footer() + " · " + generated;
                    cell(cs, fonts, foot, 0f, 380f, MARGIN - 10f, 8f, LabelFonts.Face.REGULAR, rtl, false);
                    cell(cs, fonts, w.page() + " " + pageNo + " " + w.of() + " " + pages, 0f, WIDTH, MARGIN - 10f, 8f,
                        LabelFonts.Face.REGULAR, rtl, true);
                }
            } while (i < groups.size());
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            doc.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException("Bazar price sheet render failed", e);
        }
    }

    /**
     * Arabic sheets use numeric dates (20/11/2026): Arabic month names next to a Latin location name or "Traced" are
     * re-ordered by the bidi algorithm into an unreadable line.
     */
    private static final DateTimeFormatter NUMERIC_DATE = DateTimeFormatter.ofPattern("d/M/yyyy", Locale.ENGLISH);
    private static final DateTimeFormatter NUMERIC_TIME = DateTimeFormatter.ofPattern("d/M/yyyy HH:mm", Locale.ENGLISH);

    /** "Zamalek Bazar · 20 Nov 2026 – 22 Nov 2026" (Arabic: "… · 20/11/2026 – 22/11/2026"). */
    static String place(BazarCatalogService.Catalog c, boolean rtl) {
        DateTimeFormatter f = rtl ? NUMERIC_DATE : DateTimeFormatter.ofPattern("d MMM yyyy", Locale.ENGLISH);
        List<String> parts = new ArrayList<>();
        if (c.locationName() != null) parts.add(c.locationName());
        if (c.startsOn() != null) {
            String from = LocalDate.parse(c.startsOn()).format(f);
            String to = c.endsOn() == null ? from : LocalDate.parse(c.endsOn()).format(f);
            parts.add(from.equals(to) ? from : from + " – " + to);
        }
        return String.join(" · ", parts);
    }

    /** The sizes still at the bazar ("S · M · L"); none left → "Sold out"; a product without sizes → "—". */
    static String sizes(BazarCatalogService.Group g, Words w) {
        List<String> left = g.sizes().stream().filter(s -> s.price() != null && s.left() > 0)
            .map(s -> s.size() == null ? null : s.size()).toList();
        if (left.isEmpty()) return w.soldOut();
        List<String> named = left.stream().filter(Objects::nonNull).distinct().toList();
        return named.isEmpty() ? "—" : String.join(" · ", named);
    }

    /** "960 EGP", or "800–960 EGP" when the sizes differ. */
    static String price(BazarCatalogService.Group g, Words w) {
        List<BigDecimal> p = g.sizes().stream().map(BazarCatalogService.Size::price).filter(Objects::nonNull).toList();
        BigDecimal min = p.stream().min(BigDecimal::compareTo).orElseThrow();
        BigDecimal max = p.stream().max(BigDecimal::compareTo).orElseThrow();
        String range = min.compareTo(max) == 0 ? money(min) : money(min) + "–" + money(max);
        return range + " " + w.egp();
    }

    static String money(BigDecimal v) {
        DecimalFormat f = new DecimalFormat("#,##0.##", DecimalFormatSymbols.getInstance(Locale.ENGLISH));
        f.setRoundingMode(RoundingMode.HALF_UP);
        return f.format(v);
    }

    private static float header(PDPageContentStream cs, LabelFonts.Loaded fonts, Words w, float y, boolean rtl)
            throws IOException {
        String[] head = {w.number(), w.product(), w.colour(), w.sizes(), w.price()};
        for (int col = 0; col < head.length; col++) {
            cell(cs, fonts, head[col], COL_X[col], COL_W[col], y, 8.5f, LabelFonts.Face.BOLD, rtl, COL_END[col]);
        }
        rule(cs, y - 7f, 0.6f);
        return y - ROW_H;
    }

    private static void rule(PDPageContentStream cs, float y, float width) throws IOException {
        cs.setLineWidth(width);
        cs.moveTo(MARGIN, y);
        cs.lineTo(MARGIN + WIDTH, y);
        cs.stroke();
    }

    /**
     * One cell's text: Arabic shaped + bidi-ordered, single-font runs, cut with "…" to fit. {@code end}: aligned to
     * the column's end (right in LTR). An Arabic sheet mirrors the column and flips the alignment.
     */
    private static void cell(PDPageContentStream cs, LabelFonts.Loaded fonts, String logical, float colX, float colW,
                             float y, float size, LabelFonts.Face latin, boolean rtl, boolean end) throws IOException {
        String s = logical == null ? "" : logical;
        List<LabelFonts.Run> runs = LabelFonts.runs(LabelTextFitter.display(s), latin);
        while (LabelFonts.width(runs, size) > colW && s.length() > 1) {
            s = s.substring(0, s.length() - 1);
            runs = LabelFonts.runs(LabelTextFitter.display(s.strip() + "…"), latin);
        }
        float width = LabelFonts.width(runs, size);
        float left = rtl ? MARGIN + WIDTH - colX - colW : MARGIN + colX;
        boolean alignRight = rtl != end;
        float x = alignRight ? left + colW - width : left;
        for (LabelFonts.Run run : runs) {
            cs.beginText();
            cs.setFont(fonts.font(run.face()), size);
            cs.newLineAtOffset(x, y);
            cs.showText(run.text());
            cs.endText();
            x += LabelFonts.width(List.of(run), size);
        }
    }
}
