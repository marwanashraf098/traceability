/**
 * Bazar U1b — the event report as an A4 PDF, PAGE 1 only (design/bazar-v2 V2_ReportPDF1): the header, four tiles (money
 * in, sell-through, sales, below Shopify prices), money by day (sales, revenue, should have, counted, difference),
 * money by payment method per day, the day closes' notes, and pieces sold per hour. Read-only, built from the same
 * numbers as GET /report and the day list (BazarReportService); nothing new is computed except "below Shopify prices".
 * PDFBox with the labels' embedded Noto Sans + Noto Sans Arabic, like {@link BazarPriceSheet}; Arabic mirrors.
 */
public final class BazarReportPdf {

    private BazarReportPdf() {}

    /** Everything page 1 shows. {@code days}: the day list's rows (BazarDayService.days). */
    public record Data(Map<String, Object> report, List<Map<String, Object>> days, List<String> methods,
                       BigDecimal belowShopify, String transferCode) {}

    private record Words(String subtitle, String soldDay, String soldDays, String counted, String soldThrough, String ofPieces,
                         String sales, String avg, String belowShopify, String vsShopify, String byDay, String day,
                         String salesCol, String revenue, String shouldHave, String countedCol, String difference,
                         String balanced, String notClosed, String total, String byMethod, String method,
                         String hours, String busiest, String note, String footer, String page,
                         String cash, String card, String instapay, String noSales) {}

    private static final Words EN = new Words("Bazar event report", "SOLD · 1 DAY", "SOLD · %d DAYS", "Counted %s", "SOLD THROUGH",
        "%d of %d pieces", "SALES", "avg %s", "BELOW SHOPIFY", "vs Shopify prices", "MONEY BY DAY", "Day", "Sales",
        "Revenue", "Should have", "Counted", "Difference", "Balanced", "Not closed", "Total", "BY PAYMENT METHOD",
        "Method", "PIECES SOLD PER HOUR · ALL DAYS", "Busiest %s (%d pieces).", "note", "generated by Traced",
        "Page 1 of 1", "Cash", "Card", "InstaPay", "No sales yet.");
    private static final Words AR = new Words("تقرير البازار", "المبيعات · يوم واحد", "المبيعات · %d أيام", "المعدود %s", "نسبة البيع",
        "%d من %d قطعة", "المبيعات", "متوسط %s", "أقل من Shopify", "مقارنة بأسعار Shopify", "المال حسب اليوم", "اليوم",
        "مبيعات", "الإيراد", "المفروض", "المعدود", "الفرق", "مطابق", "لم يُغلق", "الإجمالي", "حسب طريقة الدفع",
        "الطريقة", "القطع المباعة في الساعة · كل الأيام", "الأكثر ازدحامًا %s (%d قطعة).", "ملاحظة", "من Traced",
        "صفحة 1 من 1", "نقدًا", "بطاقة", "إنستاباي", "لا توجد مبيعات بعد.");

    private static final float MARGIN = 40f;
    private static final float WIDTH = PDRectangle.A4.getWidth() - 2 * MARGIN;   // 515
    private static final Color INK = new Color(0x0D, 0x11, 0x17), MUTED = new Color(0x6B, 0x72, 0x80),
        LINE = new Color(0xE5, 0xE7, 0xEB), BAR = new Color(0xCB, 0xD5, 0xE1), BLUE = new Color(0x25, 0x63, 0xEB),
        RED = new Color(0xB9, 0x1C, 0x1C), GREEN = new Color(0x15, 0x80, 0x3D), DARK = new Color(0x11, 0x18, 0x27);

    @SuppressWarnings("unchecked")
    public static byte[] pdf(Data d, String lang) {
        boolean rtl = BazarPriceSheet.arabic(lang);
        Words w = rtl ? AR : EN;
        Map<String, Object> r = d.report();
        Map<String, Object> ev = (Map<String, Object>) r.get("event");
        List<Map<String, Object>> hours = (List<Map<String, Object>>) r.get("busiest_hours");
        try (PDDocument doc = new PDDocument()) {
            LabelFonts.Loaded fonts = new LabelFonts.Loaded(doc);
            PDPage page = new PDPage(PDRectangle.A4);
            doc.addPage(page);
            try (PDPageContentStream cs = new PDPageContentStream(doc, page)) {
                Pen p = new Pen(cs, fonts, rtl);
                float y = PDRectangle.A4.getHeight() - MARGIN - 10f;

                // Header.
                p.text("traced", 0, 200, y, 16f, true, INK, false);
                p.text(str(ev.get("name")), 0, WIDTH, y, 16f, true, INK, true);
                y -= 16f;
                p.text(w.subtitle(), 0, 200, y, 9f, false, MUTED, false);
                p.text(place(ev, d.transferCode(), rtl), 0, WIDTH, y, 9f, false, MUTED, true);
                y -= 12f;
                p.rule(y, 1.2f, INK);
                y -= 22f;

                // Four tiles.
                int dayCount = Math.max(1, d.days().size());
                BigDecimal moneyIn = num(r.get("money_in"));
                BigDecimal counted = BigDecimal.ZERO, diff = BigDecimal.ZERO;
                boolean anyClosed = false;
                for (Map<String, Object> day : d.days()) {
                    Map<String, Object> c = (Map<String, Object>) day.get("close");
                    if (c == null) continue;
                    anyClosed = true;
                    for (Map<String, Object> m : methodRows(c)) {
                        counted = counted.add(num(m.get("entered")));
                        diff = diff.add(num(m.get("difference")));
                    }
                }
                Integer sales = (Integer) r.get("sales");
                float tileW = (WIDTH - 3 * 8f) / 4f, tileH = 62f;
                String[][] tiles = {
                    {dayCount == 1 ? w.soldDay() : String.format(w.soldDays(), dayCount), money(moneyIn) + " EGP",
                        anyClosed ? String.format(w.counted(), money(counted)) + " · " + signed(diff) : ""},
                    {w.soldThrough(), pct(r.get("sell_through")),
                        String.format(w.ofPieces(), (Integer) r.get("pieces_sold"), (Integer) r.get("pieces_sent"))},
                    {w.sales(), String.valueOf(sales == null ? 0 : sales),
                        r.get("average_sale") == null ? "" : String.format(w.avg(), money(num(r.get("average_sale"))) + " EGP")},
                    {w.belowShopify(), money(d.belowShopify()), w.vsShopify()},
                };
                for (int i = 0; i < 4; i++) {
                    float x = i * (tileW + 8f);
                    boolean dark = i == 0;
                    p.box(x, y - tileH, tileW, tileH, dark ? DARK : null, dark ? null : LINE);
                    Color fg = dark ? Color.WHITE : INK, sub = dark ? BAR : MUTED;
                    p.text(tiles[i][0], x + 10, tileW - 20, y - 16f, 7.5f, true, sub, false);
                    p.text(tiles[i][1], x + 10, tileW - 20, y - 36f, i == 0 ? 15f : 17f, true, fg, false);
                    p.text(tiles[i][2], x + 10, tileW - 20, y - 52f, 7.5f, false, sub, false);
                }
                y -= tileH + 26f;

                // Money by day.
                p.text(w.byDay(), 0, WIDTH, y, 10f, true, INK, false);
                y -= 18f;
                float[] cx = {0, 140, 200, 280, 360, 440};
                float[] cwid = {130, 50, 75, 75, 75, 75};
                String[] head = {w.day(), w.salesCol(), w.revenue(), w.shouldHave(), w.countedCol(), w.difference()};
                for (int i = 0; i < head.length; i++) p.text(head[i], cx[i], cwid[i], y, 8f, false, MUTED, i > 0);
                y -= 6f;
                p.rule(y, 0.4f, LINE);
                y -= 15f;
                int salesTotal = 0;
                BigDecimal revTotal = BigDecimal.ZERO, shouldTotal = BigDecimal.ZERO, countedTotal = BigDecimal.ZERO;
                BigDecimal diffTotal = BigDecimal.ZERO;
                List<String> notes = new ArrayList<>();
                for (Map<String, Object> day : d.days()) {
                    Map<String, Object> m = (Map<String, Object>) day.get("money");
                    Map<String, Object> c = (Map<String, Object>) day.get("close");
                    int s = ((Number) m.getOrDefault("sales", 0)).intValue();
                    BigDecimal rev = num(m.get("revenue")), should = num(m.get("total"));
                    salesTotal += s;
                    revTotal = revTotal.add(rev);
                    shouldTotal = shouldTotal.add(should);
                    String label = dayLabel(str(day.get("business_day")), rtl);
                    p.text(label, cx[0], cwid[0], y, 9f, true, INK, false);
                    p.text(String.valueOf(s), cx[1], cwid[1], y, 9f, false, INK, true);
                    p.text(money(rev), cx[2], cwid[2], y, 9f, false, INK, true);
                    p.text(money(should), cx[3], cwid[3], y, 9f, false, INK, true);
                    if (c == null) {
                        p.text("—", cx[4], cwid[4], y, 9f, false, MUTED, true);
                        p.text(w.notClosed(), cx[5], cwid[5], y, 9f, false, MUTED, true);
                    } else {
                        BigDecimal ce = BigDecimal.ZERO, cd = BigDecimal.ZERO;
                        for (Map<String, Object> row : methodRows(c)) {
                            ce = ce.add(num(row.get("entered")));
                            cd = cd.add(num(row.get("difference")));
                        }
                        countedTotal = countedTotal.add(ce);
                        diffTotal = diffTotal.add(cd);
                        p.text(money(ce), cx[4], cwid[4], y, 9f, false, INK, true);
                        p.text(cd.signum() == 0 ? w.balanced() : signed(cd), cx[5], cwid[5], y, 9f, true,
                            cd.signum() == 0 ? GREEN : cd.signum() < 0 ? RED : INK, true);
                        Object note = c.get("note");
                        if (note != null && !note.toString().isBlank()) notes.add(label + " " + w.note() + ": " + note);
                    }
                    y -= 6f;
                    p.rule(y, 0.3f, LINE);
                    y -= 15f;
                }
                p.text(w.total(), cx[0], cwid[0], y, 9f, true, INK, false);
                p.text(String.valueOf(salesTotal), cx[1], cwid[1], y, 9f, true, INK, true);
                p.text(money(revTotal), cx[2], cwid[2], y, 9f, true, INK, true);
                p.text(money(shouldTotal), cx[3], cwid[3], y, 9f, true, INK, true);
                p.text(anyClosed ? money(countedTotal) : "—", cx[4], cwid[4], y, 9f, true, INK, true);
                p.text(anyClosed ? (diffTotal.signum() == 0 ? w.balanced() : signed(diffTotal)) : "—", cx[5], cwid[5], y, 9f,
                    true, diffTotal.signum() < 0 ? RED : INK, true);
                y -= 28f;

                // By payment method × day.
                p.text(w.byMethod(), 0, WIDTH, y, 10f, true, INK, false);
                y -= 18f;
                int n = d.days().size();
                float colW = n == 0 ? 0 : Math.min(90f, (WIDTH - 120f - 80f) / n);
                p.text(w.method(), 0, 110, y, 8f, false, MUTED, false);
                for (int i = 0; i < n; i++) {
                    p.text(dayShort(str(d.days().get(i).get("business_day")), rtl), 120 + i * colW, colW, y, 8f, false, MUTED, true);
                }
                p.text(w.total(), WIDTH - 80, 80, y, 8f, false, MUTED, true);
                y -= 6f;
                p.rule(y, 0.4f, LINE);
                y -= 15f;
                for (String method : d.methods()) {
                    p.text(methodName(method, w), 0, 110, y, 9f, false, INK, false);
                    BigDecimal t = BigDecimal.ZERO;
                    for (int i = 0; i < n; i++) {
                        Map<String, Object> m = (Map<String, Object>) d.days().get(i).get("money");
                        Map<String, Object> bm = (Map<String, Object>) m.get("by_method");
                        BigDecimal v = bm == null ? BigDecimal.ZERO : num(bm.get(method));
                        t = t.add(v);
                        p.text(money(v), 120 + i * colW, colW, y, 9f, false, INK, true);
                    }
                    p.text(money(t), WIDTH - 80, 80, y, 9f, true, INK, true);
                    y -= 6f;
                    p.rule(y, 0.3f, LINE);
                    y -= 15f;
                }
                for (String note : notes) {
                    y -= 4f;
                    p.text(note, 0, WIDTH, y, 8.5f, false, INK, false);
                    y -= 13f;
                }
                y -= 14f;

                // Pieces sold per hour.
                p.text(w.hours(), 0, WIDTH, y, 10f, true, INK, false);
                y -= 14f;
                if (hours == null || hours.isEmpty()) {
                    p.text(w.noSales(), 0, WIDTH, y - 10f, 9f, false, MUTED, false);
                } else {
                    float chartH = 110f, baseY = Math.max(MARGIN + 50f, y - chartH);
                    int max = 1, peakIdx = 0;
                    for (int i = 0; i < hours.size(); i++) {
                        int v = pieces(hours.get(i));
                        if (v > max) { max = v; }
                        if (v > pieces(hours.get(peakIdx))) peakIdx = i;
                    }
                    float slot = WIDTH / hours.size(), barW = Math.min(46f, slot * 0.72f);
                    for (int i = 0; i < hours.size(); i++) {
                        int v = pieces(hours.get(i));
                        float h = v == 0 ? 0 : Math.max(3f, (chartH - 22f) * v / max);
                        // The chart reads left to right in both languages (hours are a timeline).
                        float x = MARGIN + i * slot + (slot - barW) / 2f;
                        if (h > 0) p.absBox(x, baseY, barW, h, i == peakIdx ? BLUE : BAR);
                        p.absText(String.valueOf(v), x, barW, baseY + h + 4f, 8f, i == peakIdx ? BLUE : MUTED);
                        p.absText(hh(((Number) hours.get(i).get("hour")).intValue()), x, barW, baseY - 11f, 8f, MUTED);
                    }
                    p.rule(baseY - 15f, 0.4f, LINE);
                    int peakHour = ((Number) hours.get(peakIdx).get("hour")).intValue();
                    p.text(String.format(w.busiest(), hh(peakHour) + "–" + hh(peakHour + 1), pieces(hours.get(peakIdx))),
                        0, WIDTH, baseY - 30f, 8.5f, false, MUTED, false);
                }

                // Footer.
                String generated = LocalDateTime.now(ZoneId.of("Africa/Cairo"))
                    .format(DateTimeFormatter.ofPattern(rtl ? "d/M/yyyy HH:mm" : "d MMM yyyy HH:mm", Locale.ENGLISH));
                p.rule(MARGIN + 6f, 0.4f, LINE);
                p.text(w.footer() + " · " + generated, 0, 360, MARGIN - 8f, 8f, false, MUTED, false);
                p.text(w.page(), 0, WIDTH, MARGIN - 8f, 8f, false, MUTED, true);
            }
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            doc.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException("Bazar report PDF render failed", e);
        }
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> methodRows(Map<String, Object> close) {
        Map<String, Object> result = (Map<String, Object>) close.get("result");
        Object m = result == null ? null : result.get("methods");
        return m instanceof List<?> l ? (List<Map<String, Object>>) l : List.of();
    }

    private static int pieces(Map<String, Object> h) {
        Object p = h.get("pieces");
        return p == null ? ((Number) h.get("sales")).intValue() : ((Number) p).intValue();
    }

    private static String methodName(String m, Words w) {
        return switch (m) { case "cash" -> w.cash(); case "card" -> w.card(); case "instapay" -> w.instapay(); default -> m; };
    }

    private static String place(Map<String, Object> ev, String transferCode, boolean rtl) {
        DateTimeFormatter f = rtl ? DateTimeFormatter.ofPattern("d/M/yyyy", Locale.ENGLISH)
                                  : DateTimeFormatter.ofPattern("EEE d MMM yyyy", Locale.ENGLISH);
        List<String> parts = new ArrayList<>();
        if (ev.get("location_name") != null) parts.add(str(ev.get("location_name")));
        String from = LocalDate.parse(str(ev.get("starts_on"))).format(f);
        String to = LocalDate.parse(str(ev.get("ends_on"))).format(f);
        parts.add(from.equals(to) ? from : from + " – " + to);
        if (transferCode != null) parts.add(transferCode);
        return String.join(" · ", parts);
    }

    private static String dayLabel(String ymd, boolean rtl) {
        return LocalDate.parse(ymd).format(DateTimeFormatter.ofPattern(rtl ? "d/M" : "EEE d MMM", Locale.ENGLISH));
    }

    private static String dayShort(String ymd, boolean rtl) {
        return LocalDate.parse(ymd).format(DateTimeFormatter.ofPattern(rtl ? "d/M" : "EEE d", Locale.ENGLISH));
    }

    private static String hh(int h) { return String.format("%02d:00", h % 24); }

    private static BigDecimal num(Object o) {
        if (o == null) return BigDecimal.ZERO;
        if (o instanceof BigDecimal b) return b;
        return new BigDecimal(o.toString());
    }

    private static String str(Object o) { return o == null ? "" : o.toString(); }

    static String money(BigDecimal v) {
        DecimalFormat f = new DecimalFormat("#,##0.##", DecimalFormatSymbols.getInstance(Locale.ENGLISH));
        f.setRoundingMode(RoundingMode.HALF_UP);
        return f.format(v);
    }

    private static String signed(BigDecimal v) {
        return (v.signum() < 0 ? "−" : v.signum() > 0 ? "+" : "") + money(v.abs());
    }

    private static String pct(Object ratio) {
        if (ratio == null) return "—";
        return num(ratio).multiply(BigDecimal.valueOf(100)).setScale(0, RoundingMode.HALF_UP).toPlainString() + "%";
    }

    /** Drawing helpers: x is from the page's start edge (mirrored on an Arabic page), y from the bottom. */
    private record Pen(PDPageContentStream cs, LabelFonts.Loaded fonts, boolean rtl) {

        void text(String logical, float x, float w, float y, float size, boolean bold, Color c, boolean end) throws IOException {
            String s = logical == null ? "" : logical;
            LabelFonts.Face latin = bold ? LabelFonts.Face.BOLD : LabelFonts.Face.REGULAR;
            List<LabelFonts.Run> runs = LabelFonts.runs(LabelTextFitter.display(s), latin);
            while (LabelFonts.width(runs, size) > w && s.length() > 1) {
                s = s.substring(0, s.length() - 1);
                runs = LabelFonts.runs(LabelTextFitter.display(s.strip() + "…"), latin);
            }
            float width = LabelFonts.width(runs, size);
            float left = rtl ? MARGIN + WIDTH - x - w : MARGIN + x;
            boolean alignRight = rtl != end;
            draw(runs, alignRight ? left + w - width : left, y, size, c);
        }

        /** Centred in [x, x+w], absolute page x (the hour chart). */
        void absText(String s, float x, float w, float y, float size, Color c) throws IOException {
            List<LabelFonts.Run> runs = LabelFonts.runs(LabelTextFitter.display(s), LabelFonts.Face.REGULAR);
            draw(runs, x + (w - LabelFonts.width(runs, size)) / 2f, y, size, c);
        }

        private void draw(List<LabelFonts.Run> runs, float x, float y, float size, Color c) throws IOException {
            cs.setNonStrokingColor(c);
            for (LabelFonts.Run run : runs) {
                cs.beginText();
                cs.setFont(fonts.font(run.face()), size);
                cs.newLineAtOffset(x, y);
                cs.showText(run.text());
                cs.endText();
                x += LabelFonts.width(List.of(run), size);
            }
            cs.setNonStrokingColor(Color.BLACK);
        }

        void rule(float y, float width, Color c) throws IOException {
            cs.setStrokingColor(c);
            cs.setLineWidth(width);
            cs.moveTo(MARGIN, y);
            cs.lineTo(MARGIN + WIDTH, y);
            cs.stroke();
            cs.setStrokingColor(Color.BLACK);
        }

        void box(float x, float y, float w, float h, Color fill, Color stroke) throws IOException {
            float left = rtl ? MARGIN + WIDTH - x - w : MARGIN + x;
            cs.addRect(left, y, w, h);
            if (fill != null) {
                cs.setNonStrokingColor(fill);
                cs.fill();
                cs.setNonStrokingColor(Color.BLACK);
            } else {
                cs.setStrokingColor(stroke);
                cs.setLineWidth(0.6f);
                cs.stroke();
                cs.setStrokingColor(Color.BLACK);
            }
        }

        void absBox(float x, float y, float w, float h, Color fill) throws IOException {
            cs.addRect(x, y, w, h);
            cs.setNonStrokingColor(fill);
            cs.fill();
            cs.setNonStrokingColor(Color.BLACK);
        }
    }
}
